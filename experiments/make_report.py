"""Build plots/*.png and results/report_tables.md from results/*.json (missing results are skipped)."""
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RES, PLOTS = ROOT / "results", ROOT / "plots"
PLOTS.mkdir(exist_ok=True)

# reference palette (light): categorical slots 1-4 + text/grid tokens
C = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
INK, INK2, GRID, SURF = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
plt.rcParams.update({
    "figure.facecolor": SURF, "axes.facecolor": SURF, "savefig.facecolor": SURF,
    "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8, "axes.spines.top": False,
    "axes.spines.right": False, "font.size": 10, "axes.titlesize": 11, "axes.titleweight": "bold",
    "axes.titlecolor": INK, "legend.frameon": False, "lines.linewidth": 2, "lines.markersize": 8,
})


def load(name):
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def f(x, d=3):
    return "–" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


md = ["# Results tables (auto-generated by experiments/make_report.py)\n"]

# ---------- E1 ----------
e1 = load("e1_baseline")
if e1:
    md.append("## E1: baseline (hybrid k=3) vs logged teacher pages\n")
    rows = [[k, f(v["gain"], 4), f(v["recall"], 4), f(v["reward"], 2), f(v["diversity"]), f(v["forwards"], 1),
             f(v.get("latency_ms_mean"), 1), v["violations_total"], f(v["value_ece"], 4)]
            for k, v in e1["arms"].items()]
    md.append(table(["arm", "disc. gain", "recall@page", "page reward", "diversity", "forwards", "lat ms (MPS)",
                     "violations", "value ECE"], rows))
    if e1.get("table1"):
        md.append("\n**Table-1 analogue (λ=1, S, test set):**\n")
        md.append(table(["metric", "with pretraining", "without"],
                        [[m, f(e1["table1"].get("wbc", {}).get(m), 4), f(e1["table1"].get("wbc_scratch", {}).get(m), 4)]
                         for m in ("wbc_loss", "row_auc", "entity_auc")]))

# ---------- E2 ----------
e2 = load("e2_profile")
if e2:
    md.append("\n## E2: batch-1 latency breakdown (ms per page)\n")
    rows = [[r["dev"], r["size"], r["hist_cap"], r["ctx_len"], r["fill"], r["k"], r["forwards"], f(r["e2e_ms"], 1),
             f(r.get("prefill_ms"), 1), f(r.get("forward_ms"), 1), f(r.get("mask_ms"), 1), f(r.get("select_ms"), 1),
             f(r["prefill_share"], 2)] for r in e2]
    md.append(table(["dev", "model", "hist", "ctx tok", "fill", "k", "fwd", "e2e", "prefill", "decode fwd", "mask",
                     "select", "prefill share"], rows))
    for dev in sorted({r["dev"] for r in e2}):
        sel = [r for r in e2 if r["dev"] == dev and r["fill"] == "ar" and r["k"] == 3]
        if not sel:
            continue
        fig, ax = plt.subplots(figsize=(7.5, 3.6))
        labels = [f"{r['size']} · {r['hist_cap']}" for r in sel]
        phases = [("prefill_ms", "prefill"), ("forward_ms", "decode forwards"), ("mask_ms", "masks"), ("select_ms", "select / sync")]
        left = [0.0] * len(sel)
        for (key, name), col in zip(phases, C):
            vals = [r.get(key, 0) for r in sel]
            ax.barh(labels, vals, left=left, color=col, label=name, height=0.6, edgecolor=SURF, linewidth=2)
            left = [l + v for l, v in zip(left, vals)]
        for y, tot in enumerate(left):
            ax.text(tot + max(left) * 0.01, y, f"{tot:.0f} ms", va="center", color=INK2, fontsize=9)
        ax.set_xlabel("ms per page (phase-synced)")
        ax.set_ylabel("model · history actions")
        ax.set_title(f"Where serving time goes — hybrid k=3, {dev.upper()}")
        ax.legend(ncol=4, loc="upper center", bbox_to_anchor=(0.5, -0.18))
        ax.grid(axis="y", visible=False)
        fig.tight_layout()
        fig.savefig(PLOTS / f"e2_breakdown_{dev}.png", dpi=160)
        plt.close(fig)

