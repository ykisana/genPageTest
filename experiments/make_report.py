# ---------- Significance: Δ quality (95% CI) vs speedup, per lambda ----------
NAMES = {"hybrid_k1": "GenPage k=1", "hybrid_k10": "GenPage full AR (k=10)", "mtp_direct_k3": "MTP-direct k=3",
         "skeleton_k3": "skeleton + parallel fill", "hybrid_k3_ctrl3": "GenPage k=3, +1 pretrain epoch",
         "parallel_indep": "parallel, independent slots", "parallel_joint": "parallel, joint slots",
         "teacher": "teacher (logged)"}
CLS = {"hybrid_k1": 0, "hybrid_k10": 0, "hybrid_k3_ctrl3": 0, "mtp_direct_k3": 1, "skeleton_k3": 1,
       "parallel_indep": 2, "parallel_joint": 2}
sig = {lam: load(f"significance_lam{lam}") for lam in (0, 1, 2)}
sig = {k: v for k, v in sig.items() if v}
if sig:
    md.append("\n## Paired significance vs GenPage hybrid k=3 (1000 test pages, 95% bootstrap CI)\n")
    for lam, d in sig.items():
        rows = []
        for name, r in d["vs_hybrid_k3"].items():
            lo, hi = r["ci95"]
            rows.append([NAMES.get(name, name), f"{r['d_gain']:+.4f}", f"[{lo:+.4f}, {hi:+.4f}]", f"{r['rel']:+.1%}",
                         "yes" if (lo > 0 or hi < 0) else "no", f(r.get("latency_ratio"), 2), f(r.get("fwd"), 1)])
        md.append(f"\n**λ={lam}** (n={d['n']})\n")
        md.append(table(["arm", "Δ gain", "95% CI", "relative", "significant", "speedup (MPS)", "forwards"], rows))
    lam = 1 if 1 in sig else next(iter(sig))
    items = [(n, r) for n, r in sig[lam]["vs_hybrid_k3"].items() if "latency_ratio" in r]
    fig, ax = plt.subplots(figsize=(8.2, 4.6))
    ax.axhline(0, color=INK2, linewidth=1)
    ax.axvline(1, color=INK2, linewidth=1, linestyle="--")
    names = ["GenPage variant (same model)", "lossy GenPage decoder", "Jev-style parallel decision model"]
    seen = set()
    for n, r in items:
        c = CLS.get(n, 0)
        lo, hi = r["ci95"]
        ax.errorbar(r["latency_ratio"], r["d_gain"], yerr=[[r["d_gain"] - lo], [hi - r["d_gain"]]], fmt="o",
                    color=C[c], ecolor=C[c], elinewidth=2, capsize=4, markersize=8, markeredgecolor=SURF,
                    label=names[c] if c not in seen else None, zorder=3)
        seen.add(c)
        ax.annotate(NAMES.get(n, n), (r["latency_ratio"], hi), xytext=(0, 6), textcoords="offset points",
                    ha="center", color=INK2, fontsize=8)
    ax.plot([1], [0], marker="D", color=INK, markersize=7, zorder=4)
    ax.annotate("paper's hybrid k=3\n(reference)", (1, 0), xytext=(8, -8), textcoords="offset points",
                ha="left", va="top", color=INK, fontsize=8)
    ax.set_xlabel("wall-clock speedup vs hybrid k=3 (MPS, batch 1)")
    ax.set_ylabel("Δ discounted page gain (95% CI)")
    ax.set_title(f"Quality change vs speedup, every arm (λ={lam}, {sig[lam]['n']} paired test pages)")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=3)
    fig.tight_layout()
    fig.savefig(PLOTS / "quality_vs_speedup.png", dpi=160)
    plt.close(fig)
    # E7 with CIs across lambda
    fig, ax = plt.subplots(figsize=(6.4, 3.8))
    ax.axhline(0, color=INK2, linewidth=1)
    for ci, n in enumerate(("parallel_indep", "parallel_joint")):
        pts = [(lam, d["vs_hybrid_k3"][n]) for lam, d in sorted(sig.items()) if n in d["vs_hybrid_k3"]]
        if not pts:
            continue
        xs = [p[0] + (ci - 0.5) * 0.08 for p in pts]
        ys = [p[1]["d_gain"] for p in pts]
        err = [[y - p[1]["ci95"][0] for y, p in zip(ys, pts)], [p[1]["ci95"][1] - y for y, p in zip(ys, pts)]]
        ax.errorbar(xs, ys, yerr=err, fmt="o-", color=C[ci + 1], capsize=4, linewidth=2, label=NAMES[n])
    ax.set_xticks(sorted(sig))
    ax.set_xlabel("teacher intra-row dependency λ")
    ax.set_ylabel("Δ gain vs GenPage hybrid k=3")
    ax.set_title("One-pass decision model vs autoregression")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.18), ncol=2)
    fig.tight_layout()
    fig.savefig(PLOTS / "e7_parallel_ci.png", dpi=160)
    plt.close(fig)

